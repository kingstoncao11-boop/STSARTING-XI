export function getCategoryFromPosition(pos: PositionCode): 'GK' | 'DEF' | 'MID' | 'ATT' {
  if (pos === 'GK') return 'GK';
  if (['CB', 'LB', 'RB', 'LWB', 'RWB', 'SW'].includes(pos)) return 'DEF';
  if (['DM', 'CM', 'AM', 'LM', 'RM'].includes(pos)) return 'MID';
  return 'ATT';
}

