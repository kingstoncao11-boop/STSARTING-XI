export function getCategoryFromPosition(position: string): 'GK' | 'DEF' | 'MID' | 'ATT' {
  const p = position.toUpperCase();
  if (p === 'GK') return 'GK';
  if (['CB', 'LB', 'RB', 'LWB', 'RWB', 'SW', 'LCB', 'RCB'].includes(p)) return 'DEF';
  if (['CDM', 'CM', 'CAM', 'LM', 'RM', 'LCM', 'RCM', 'LDM', 'RDM', 'DM', 'AM'].includes(p)) return 'MID';
  return 'ATT';
}
