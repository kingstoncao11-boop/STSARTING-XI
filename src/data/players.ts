// Immutable O(1) Player Registry by unique, canonical ID
export const PLAYER_REGISTRY_BY_ID: Map<string, Player> = new Map(
  INITIAL_PLAYERS.map((p) => [p.id, Object.freeze({ ...p })])
);

/**
 * Strict canonical lookup: Returns player only if exact immutable ID matches.
 * NEVER does fuzzy name search or returns an arbitrary fallback.
 */
export function getPlayerById(id: string): Player | undefined {
  return PLAYER_REGISTRY_BY_ID.get(id);
}

/**
 * Safe retrieval: If player is missing, returns a neutral placeholder rather
 * than ever substituting another player.
 */
export function requirePlayerById(id: string): Player {
  const found = PLAYER_REGISTRY_BY_ID.get(id);
  if (found) return found;
  return {
    id,
    name: 'Player ' + id,
    shortName: 'Player',
    position: 'CM',
    category: 'MID',
    secondaryPositions: [],
    club: 'Free Agent',
    league: 'None',
    nationality: 'World',
    shirtNumber: 0,
    rating: 75,
    avatar: '', // Empty photo triggers neutral initials placeholder, NEVER wrong player
  };
}

